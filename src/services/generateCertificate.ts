import type { PayloadRequest, Where } from 'payload'

import { randomUUID } from 'crypto'

import { createPDF } from '../utilities/createPDF.js'
import {
  asSlug,
  findDoc,
  getSlugs,
  type ID,
  type LMSDoc,
  LMSError,
  sameId,
  toId,
  withTransaction,
} from './shared.js'

type CertificateArgs = {
  certificateId: ID
  courseId: ID
  req: PayloadRequest
  userId: ID
}

export type CertificatePDF = {
  data: Buffer
  /** A readable name for an email attachment, for example `Certificate - Sleep Basics.pdf`. */
  filename: string
  mimeType: 'application/pdf'
}

export type GenerateCertificateResult = {
  /** The private `documents` entry holding the certificate PDF. */
  document: LMSDoc
  /** @deprecated Same as `document`. */
  media: LMSDoc
  status: 'created' | 'existing'
}

/**
 * File name used before 2.0, built from IDs. Only used to find and remove PDFs generated by older
 * versions, which were stored in the public media collection.
 */
export const getCertificateFileName = ({ certificateId, courseId, userId }: { certificateId: ID; courseId: ID; userId: ID }) =>
  `certificate-${courseId}-${certificateId}-${userId}.pdf`

const loadAward = async (req: PayloadRequest, { certificateId, courseId, userId }: Omit<CertificateArgs, 'req'>) => {
  const user = await findDoc(req, getSlugs(req).students, userId, 'User')
  const certificates: LMSDoc[] = Array.isArray(user.certificates) ? user.certificates : []
  const awarded = certificates.find(
    (entry) => sameId(entry.certificate, certificateId) && sameId(entry.course, courseId),
  )
  if (!awarded) {
    throw new LMSError('This certificate has not been awarded for this course.', 403)
  }
  return { awarded, certificates, user }
}

// e.g. "26 November 2025"
const formatDate = (value: unknown): string =>
  new Date(typeof value === 'string' && !Number.isNaN(Date.parse(value)) ? value : Date.now()).toLocaleDateString(
    'en-US',
    { day: 'numeric', month: 'long', year: 'numeric' },
  )

/**
 * Renders the PDF for an award. Dated with the award's completion date, so the same award always
 * produces the same certificate.
 */
const buildPDF = async (req: PayloadRequest, user: LMSDoc, awarded: LMSDoc, courseId: ID, certificateId: ID) => {
  const slugs = getSlugs(req)
  const course = await findDoc(req, slugs.courses, courseId, 'Course')
  // depth 1 populates the template image and authors
  const certificate = (await req.payload.findByID({
    id: certificateId,
    collection: asSlug(slugs.certificates),
    depth: 1,
    disableErrors: true,
    req,
  })) as LMSDoc | null
  if (!certificate) {
    throw new LMSError('Certificate not found.', 404)
  }
  if (!user.firstName || !user.lastName) {
    throw new LMSError('User name is incomplete.', 400)
  }
  if (!course.title) {
    throw new LMSError('Course title is missing.', 400)
  }

  const author = Array.isArray(certificate.authors) ? certificate.authors[0] : undefined
  const pdf = await createPDF({
    authorName:
      author && typeof author === 'object' ? `${author.firstName || ''} ${author.lastName || ''}`.trim() : undefined,
    certificateNumber: `CERT-${course.id}-${certificate.id}-${user.id}`,
    completionDate: formatDate(awarded.completedDate),
    courseTitle: course.title,
    description: certificate.description || 'Certificate of Completion',
    fontFamily: 'Poppins',
    studentName: `${user.firstName} ${user.lastName}`,
    templateImage: certificate.template?.url || '',
  })
  return { course, data: Buffer.from(pdf) }
}

const attachmentName = (courseTitle: string) =>
  `Certificate - ${courseTitle.replace(/[^\w\s-]/g, '').replace(/\s+/g, ' ').trim() || 'Course'}.pdf`

/**
 * Returns the PDF for an awarded certificate without storing anything. Use it to attach the
 * certificate to an email, so the email holds no link that someone else could open.
 */
export const renderCertificatePDF = async ({ certificateId, courseId, req, userId }: CertificateArgs): Promise<CertificatePDF> => {
  const { awarded, user } = await loadAward(req, { certificateId, courseId, userId })
  const { course, data } = await buildPDF(req, user, awarded, courseId, certificateId)
  return { data, filename: attachmentName(course.title), mimeType: 'application/pdf' }
}

/**
 * Returns the stored certificate PDF for an award, creating it on first request. The PDF lives in
 * the private documents collection, owned by the student. Public copies left in the media
 * collection by older versions are deleted when the private one is created.
 */
export const generateCertificate = ({
  certificateId,
  courseId,
  req,
  userId,
}: CertificateArgs): Promise<GenerateCertificateResult> =>
  withTransaction(req, async () => {
    const slugs = getSlugs(req)
    const { awarded, certificates, user } = await loadAward(req, { certificateId, courseId, userId })

    const documentId = toId(awarded.document)
    if (documentId !== undefined) {
      const existing = (await req.payload.findByID({
        id: documentId,
        collection: asSlug(slugs.documents),
        depth: 0,
        disableErrors: true,
        req,
      })) as LMSDoc | null
      if (existing) {
        return { document: existing, media: existing, status: 'existing' }
      }
    }

    const { course, data } = await buildPDF(req, user, awarded, courseId, certificateId)
    const document = (await req.payload.create({
      collection: asSlug(slugs.documents),
      data: {
        owner: user.id,
        title: `Certificate - ${course.title} - ${user.firstName} ${user.lastName}`,
      },
      file: { name: `certificate-${randomUUID()}.pdf`, data, mimetype: 'application/pdf', size: data.length },
      req,
    })) as LMSDoc

    await deletePublicCopies(req, { awarded, certificateId, courseId, userId: user.id })

    await req.payload.update({
      id: user.id,
      collection: asSlug(slugs.students),
      data: {
        certificates: certificates.map((entry) => ({
          ...entry,
          certificate: toId(entry.certificate),
          course: toId(entry.course),
          document: entry === awarded ? document.id : (toId(entry.document) ?? null),
          file: entry === awarded ? null : (toId(entry.file) ?? null),
        })),
      },
      // Linking the PDF is not a new award
      context: { lmsCertificateFile: true },
      req,
    })

    req.payload.logger.info(`Created certificate ${document.id} for user ${user.id} for course ${course.id}`)
    return { document, media: document, status: 'created' }
  })

/**
 * Removes the public media copies of this certificate made by older versions: the one linked from
 * the award and any named with the 1.x pattern.
 */
const deletePublicCopies = async (
  req: PayloadRequest,
  { awarded, certificateId, courseId, userId }: { awarded: LMSDoc; certificateId: ID; courseId: ID; userId: ID },
) => {
  const media = getSlugs(req).media
  if (!req.payload.collections[asSlug(media)]) {return}

  const linkedId = toId(awarded.file)
  const where: Where = {
    or: [
      { filename: { equals: getCertificateFileName({ certificateId, courseId, userId }) } },
      ...(linkedId !== undefined ? [{ id: { equals: linkedId } }] : []),
    ],
  }
  await req.payload.delete({ collection: asSlug(media), req, where })
}
