import type { PayloadRequest } from 'payload'

import { randomUUID } from 'crypto'

import { createPDF } from '../utilities/createPDF.js'
import {
  asSlug,
  findDoc,
  getSlugs,
  type ID,
  type LMSDoc,
  LMSError,
  sameId,
  toId,
  withTransaction,
} from './shared.js'

type GenerateCertificateArgs = {
  certificateId: ID
  courseId: ID
  req: PayloadRequest
  userId: ID
}

export type GenerateCertificateResult = {
  /** The media document holding the certificate PDF. */
  media: LMSDoc
  status: 'created' | 'existing'
}

/**
 * File name used before 2.0, built from IDs. Only used to find PDFs generated by older versions;
 * new PDFs get a random name.
 */
export const getCertificateFileName = ({ certificateId, courseId, userId }: { certificateId: ID; courseId: ID; userId: ID }) =>
  `certificate-${courseId}-${certificateId}-${userId}.pdf`

/**
 * Returns the certificate PDF for a course, creating it on first request. The user must have
 * been awarded this certificate for this course.
 */
export const generateCertificate = ({
  certificateId,
  courseId,
  req,
  userId,
}: GenerateCertificateArgs): Promise<GenerateCertificateResult> =>
  withTransaction(req, async () => {
    const slugs = getSlugs(req)
    const user = await findDoc(req, slugs.students, userId, 'User')

    const certificates: LMSDoc[] = Array.isArray(user.certificates) ? user.certificates : []
    const awarded = certificates.find(
      (entry) => sameId(entry.certificate, certificateId) && sameId(entry.course, courseId),
    )
    if (!awarded) {
      throw new LMSError('This certificate has not been awarded for this course.', 403)
    }

    const saveFileOnAward = async (mediaId: ID) => {
      await req.payload.update({
        id: user.id,
        collection: asSlug(slugs.students),
        data: {
          certificates: certificates.map((entry) => ({
            ...entry,
            certificate: toId(entry.certificate),
            course: toId(entry.course),
            file: entry === awarded ? mediaId : toId(entry.file),
          })),
        },
        // Saving the file reference is not a new award
        context: { lmsCertificateFile: true },
        req,
      })
    }

    const fileId = toId(awarded.file)
    if (fileId !== undefined) {
      const media = await req.payload.findByID({
        id: fileId,
        collection: asSlug(slugs.media),
        depth: 0,
        disableErrors: true,
        req,
      })
      if (media) {
        return { media: media as LMSDoc, status: 'existing' }
      }
    }

    const { docs: legacy } = await req.payload.find({
      collection: asSlug(slugs.media),
      depth: 0,
      limit: 1,
      req,
      where: {
        filename: { equals: getCertificateFileName({ certificateId, courseId, userId: user.id }) },
      },
    })
    if (legacy[0]) {
      await saveFileOnAward(legacy[0].id)
      return { media: legacy[0] as LMSDoc, status: 'existing' }
    }

    const course = await findDoc(req, slugs.courses, courseId, 'Course')
    // depth 1 populates the template image and authors
    const certificate = (await req.payload.findByID({
      id: certificateId,
      collection: asSlug(slugs.certificates),
      depth: 1,
      disableErrors: true,
      req,
    })) as LMSDoc | null
    if (!certificate) {
      throw new LMSError('Certificate not found.', 404)
    }
    if (!user.firstName || !user.lastName) {
      throw new LMSError('User name is incomplete.', 400)
    }
    if (!course.title) {
      throw new LMSError('Course title is missing.', 400)
    }

    const author = Array.isArray(certificate.authors) ? certificate.authors[0] : undefined
    const pdf = await createPDF({
      authorName:
        author && typeof author === 'object'
          ? `${author.firstName || ''} ${author.lastName || ''}`.trim()
          : undefined,
      certificateNumber: `CERT-${course.id}-${certificate.id}-${user.id}`,
      courseTitle: course.title,
      studentName: `${user.firstName} ${user.lastName}`,
      // e.g. "26 November 2025"
      completionDate: new Date().toLocaleDateString('en-US', {
        day: 'numeric',
        month: 'long',
        year: 'numeric',
      }),
      description: certificate.description || 'Certificate of Completion',
      fontFamily: 'Poppins',
      templateImage: certificate.template?.url || '',
    })

    const buffer = Buffer.from(pdf)
    const media = (await req.payload.create({
      collection: asSlug(slugs.media),
      data: {
        title: `Certificate - ${course.title} - ${user.firstName} ${user.lastName}`,
      },
      file: {
        name: `certificate-${randomUUID()}.pdf`,
        data: buffer,
        mimetype: 'application/pdf',
        size: buffer.length,
      },
      req,
    })) as LMSDoc

    await saveFileOnAward(media.id)

    req.payload.logger.info(`Created certificate ${media.id} for user ${user.id} for course ${course.id}`)
    return { media, status: 'created' }
  })
